"""Evidence packs: a record of abusive payments a victim can take to police, a
court (protection order) or a lawyer.

Rules this module enforces:
  * Only with the recipient's consent, for one sender and a stated purpose.
    The caller checks consent; the pack records which consent it relied on.
  * Facts come from the stored evidence log, not from a language model. Granite's
    brief may be attached, but only marked as an unchecked AI draft.
  * Minimal disclosure: the recipient's safe-contact preferences are never
    included, and parties appear as the bank's pseudonymous references.
  * Tamper-evident: the pack is canonical JSON, fingerprinted with SHA-256 and
    signed with the bank's Ed25519 key. Anyone with the bank's public key can
    check that not a single character has changed since it was issued.
"""
from __future__ import annotations

import hashlib
import json
import os
from datetime import datetime, timezone
from pathlib import Path

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

FORMAT = "safepay-evidence-pack/1"
SIGN_KEY_FILE = Path(os.environ.get("SAFEPAY_SIGN_KEY_FILE", Path.home() / ".safepay" / "sign_key"))
PURPOSES = {
    "police": "Report to police",
    "protection_order": "Application for a protection order",
    "legal_advice": "Legal advice",
}
DISCLAIMERS = [
    "Generated by the SafePay prototype from synthetic demonstration data.",
    "Harm and threat scores are model outputs that helped flag the payments. They are not findings of fact.",
    "Any AI-drafted summary is a draft only and must be checked against the timeline before use.",
    "Party references are pseudonymous. The bank maps them to account holders under its own legal process.",
]


def utc(ts: float | None) -> str | None:
    return datetime.fromtimestamp(ts, timezone.utc).isoformat(timespec="seconds") if ts else None


def _plain(obj):
    # JSON has one number type: a browser reads 1.0 back as 1, so whole floats are written as integers.
    if isinstance(obj, float) and obj.is_integer():
        return int(obj)
    if isinstance(obj, dict):
        return {k: _plain(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_plain(v) for v in obj]
    return obj


def canonical(obj) -> bytes:
    return json.dumps(_plain(obj), sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")


# -- signing key -------------------------------------------------------------------
def signing_key(path: Path = SIGN_KEY_FILE) -> Ed25519PrivateKey:
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(Ed25519PrivateKey.generate().private_bytes_raw())
        path.chmod(0o600)
    return Ed25519PrivateKey.from_private_bytes(path.read_bytes())


def public_key_hex(key: Ed25519PrivateKey) -> str:
    return key.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw).hex()


# -- build, sign, verify -------------------------------------------------------------
def build(case: dict, evidence: list[dict], facts: dict, consent: dict, chain: dict, analyst: str,
          model_version: str, summary: str | None = None, summary_by: str | None = None) -> dict:
    """The unsigned pack body. `evidence` rows carry decrypted `reference` text."""
    timeline = []
    for i, e in enumerate(evidence, 1):
        timeline.append({
            "n": i,
            "time_utc": utc(e["ts"]),
            # Messages captured from the sender's recent payments when the case opened carry no amount.
            "amount": round(e["amount"], 2) if e["amount"] else None,
            "message": e["reference"],
            "shown_to_recipient": not e["hidden"],
            "harm_score": round(e["harm"], 3),
            "threat_score": round(e["threat"], 3),
        })
    return {
        "format": FORMAT,
        "generated_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "generated_by": {"system": "SafePay", "model_version": model_version, "analyst": analyst},
        "purpose": PURPOSES.get(consent["purpose"], consent["purpose"]),
        "consent": {"given_by": "the recipient (account holder)", "given_utc": utc(consent["granted"]),
                    "scope": "payments from one sender", "consent_ref": consent["id"]},
        "parties": {"sender_ref": case["sender"], "recipient_ref": case["recipient"]},
        "case": {"case_ref": case["id"], "opened_utc": utc(case["opened"]), "priority": case["priority"],
                 "status": case["status"]},
        "pattern": {k: v for k, v in facts.items() if not k.startswith("model_")},
        "model_assessment": {"risk_score": round(case["score"], 3),
                             "reasons": json.loads(case["reasons"] or "[]")[:8]},
        "timeline": timeline,
        "ai_draft_summary": ({"text": summary, "generated_by": summary_by,
                              "status": "AI draft, not checked by a person"} if summary else None),
        "integrity": {"evidence_log_entries": chain["entries"], "evidence_log_intact": chain["intact"],
                      "evidence_log_head_sha256": chain["head"]},
        "disclaimers": DISCLAIMERS,
    }


def sign(body: dict, key: Ed25519PrivateKey) -> dict:
    data = canonical(body)
    return {"pack": body, "sha256": hashlib.sha256(data).hexdigest(),
            "signature": {"algorithm": "Ed25519", "public_key": public_key_hex(key),
                          "value": key.sign(data).hex()}}


def verify(signed: dict, trusted_public_key_hex: str) -> dict:
    """Checks a pack against the bank's published public key (not the key inside it)."""
    try:
        data = canonical(signed["pack"])
        sha_ok = hashlib.sha256(data).hexdigest() == signed.get("sha256")
        key_ok = signed.get("signature", {}).get("public_key") == trusted_public_key_hex
        try:
            Ed25519PublicKey.from_public_bytes(bytes.fromhex(trusted_public_key_hex)).verify(
                bytes.fromhex(signed["signature"]["value"]), data)
            sig_ok = True
        except (InvalidSignature, ValueError, KeyError):
            sig_ok = False
    except (KeyError, TypeError):
        return {"valid": False, "fingerprint_matches": False, "signature_valid": False, "signed_by_this_bank": False}
    return {"valid": sha_ok and sig_ok and key_ok, "fingerprint_matches": sha_ok, "signature_valid": sig_ok,
            "signed_by_this_bank": key_ok}
